test('physical dice allow concurrent room versions but never cross recruitment IDs or clear a newer round', async () => {
  const pending = deferred<boolean>(), calls: CommandCall[] = [], first = check('round-one', 'access', 'selected'), initial = { ...game(), revision: 2, checks: [first] };
  const w = world(initial, (...args) => { calls.push(args); return pending.promise; }), c = w.mount();
  c.input('physical-die', 11); c.setGame({ ...initial, revision: 5 });
  const saving = c.ui.rollPhysical(event); expect(calls).toEqual([['roll', { checkId: 'round-one', die: 11 }, 2]]);
  const second = { ...first, id: 'round-two' }; c.setGame({ ...initial, revision: 6, checks: [second] });
  expect(c.value('physical-die')).toBeUndefined(); c.input('physical-die', 19); c.stop();
  const restored = w.mount({ ...initial, revision: 7, checks: [second] });
  pending.resolve(true); await saving; expect(restored.value('physical-die')).toBe(19); expect(restored.ui.physical.dirty).toBe(true); expect(restored.ui.physical.revision).toBe(6); w.dispose();
});


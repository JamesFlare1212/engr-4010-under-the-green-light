const bindingExpressions = new Map<string, string>();
function walk(value: unknown, visit: (node: any) => void) {
  if (!value || typeof value !== 'object') return;
  if (Array.isArray(value)) { value.forEach(item => walk(item, visit)); return; }
  const node = value as Record<string, unknown>; visit(node);
  for (const [key, item] of Object.entries(node)) if (!['expression', 'loc'].includes(key)) walk(item, visit);
}
walk(ast.html, node => {
  const id = node.attributes?.find((attribute: any) => attribute.name === 'id')?.value?.[0]?.data;
  const binding = node.attributes?.find((attribute: any) => attribute.type === 'Binding' && attribute.name === 'value');
  if (id && binding) {
    expect(binding.expression.type).toBe('SequenceExpression');
    bindingExpressions.set(id, source.slice(binding.expression.start, binding.expression.end));
  }
});

